def _is_controller(path):
    if not path.exists():
        return False
    t = path.read_text(encoding="utf-8", errors="ignore")
    return bool(re.search(r'#define\s+FW_VERSION\s+"P-', t)) and "TEST_VERSION" not in t


def _qt_version(path):
    if not path.exists():
        return (0, 0)
    m = re.search(r'#define\s+TEST_VERSION\s+"QT-(\d+)\.(\d+)"', path.read_text(encoding="utf-8", errors="ignore"))
    return (int(m.group(1)), int(m.group(2))) if m else (0, 0)


def _write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        if path.read_bytes() == data:
            return False
        path.with_name(path.name + ".bak").write_bytes(path.read_bytes())
    path.write_bytes(data)
    return True


def _speed(ini):
    if not ini.exists():
        return
    t = ini.read_text(encoding="utf-8")
    n = re.sub(r"(?m)^upload_speed\s*=\s*921600.*$", "upload_speed = 460800", t)
    if n != t:
        ini.write_text(n, encoding="utf-8")
        print(f"[repair] upload speed set to 460800 in {ini}")


def ensure_esptool_cfg(folder):
    """Removes the upload-timing file an earlier version wrote: uploads use PlatformIO's normal settings again."""
    f = Path(folder) / "esptool.cfg"
    if f.exists() and "written by quanta_repair.py" in f.read_text(encoding="utf-8", errors="ignore"):
        f.unlink()
        print(f"[repair] removed the upload timing file (back to normal upload settings): {f}")


def repair_controller(project):
    ctl = Path(project) / "src" / "main.cpp"
    if not _is_controller(ctl):
        _write(ctl, _z().read("controller/src/main.cpp"))
        print(f"[repair] {ctl} was not the controller firmware: put back P-0.0.6 (old file kept as main.cpp.bak)")
    _speed(Path(project) / "platformio.ini")
    ensure_esptool_cfg(project)


def repair_test(project):
    project = Path(project)
    found = [d for d in (project / "quanta-test", project.parent / "quanta-test") if (d / "platformio.ini").exists()]
    target = found[0] if found else project / "quanta-test"
    names = [n for n in _z().namelist() if n.startswith("quanta-test/")]
    if not found or not (target / "lib").is_dir():
        for n in names:
            _write(target / n[len("quanta-test/"):], _z().read(n))
        print(f"[repair] installed Quanta Test QT-1.6 in {target}")
    elif _qt_version(target / "src" / "main.cpp") < (1, 6):
        _write(target / "src" / "main.cpp", _z().read("quanta-test/src/main.cpp"))
        print(f"[repair] updated Quanta Test to QT-1.6 in {target}")
    _speed(target / "platformio.ini")
    ensure_esptool_cfg(target)
    return target


def repair_all(project):
    repair_controller(project)
    return repair_test(project)
